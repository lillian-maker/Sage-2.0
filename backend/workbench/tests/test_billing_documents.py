"""Contract tests: app/billing/display and app/billing/invoices/{id}/pdf (64/66 屏，D29).

The bill PDF is generated by workbench from the order snapshot; the invoice PDF is only offered once the
invoice request has been issued. Discounts live in the order snapshot (discount_minor / discount_label).
"""
from datetime import timedelta

from django.utils import timezone

from backend.commerce.models import Order, PaymentFact, ProductVersion, Quote
from backend.models import InvoiceRequest
from backend.workbench.tests.base import AppTestCase

SNAPSHOT = {'product_id': 'fixture', 'code': 'fixture-credits-5000', 'version': 1, 'kind': 'credits',
            'audience': 'personal', 'credits_quantity': '5000', 'unit_amount_minor': 49900, 'amount_minor': 44900,
            'discount_minor': 5000, 'discount_label': '加购 5,000 Credits 省 10%', 'currency': 'CNY'}


def make_order(account, user, number, snapshot=SNAPSHOT, disposition='accepted',
               reference='2026110322001000000000008821'):
    now = timezone.now()
    product, _ = ProductVersion.objects.get_or_create(
        code=snapshot['code'], version=1,
        defaults=dict(kind='credits', audience=snapshot['audience'], billing_cycle='',
                      unit_amount_minor=snapshot['unit_amount_minor'], credits_quantity='5000', state='published',
                      effective_at=now - timedelta(days=30)))
    quote = Quote.objects.create(account=account, product=product, snapshot=snapshot,
                                 amount_minor=snapshot['amount_minor'], currency='CNY',
                                 expires_at=now + timedelta(days=1))
    order = Order.objects.create(account=account, created_by=user, quote=quote, idempotency_key='fx-' + number,
                                 request_hash='fx', snapshot=snapshot, amount_minor=snapshot['amount_minor'],
                                 currency='CNY', status='fulfilled', paid_at=now, display_number=number)
    PaymentFact.objects.create(order=order, channel='alipay', merchant_reference='fx-' + number,
                               transaction_reference=reference, amount_minor=snapshot['amount_minor'],
                               currency='CNY', evidence_hash='e' * 64, disposition=disposition, paid_at=now)
    return order


class BillingDocumentTests(AppTestCase):
    def setUp(self):
        self.login(self.lillian)
        self.order = make_order(self.personal, self.lillian, 'SG-2026-11-0042')

    def display(self):
        body = self.ok(self.get('app/billing/display'))
        return body, {row['order_id']: row for row in body['orders']}

    def test_display_discount_reference_and_channel(self):
        body, rows = self.display()
        self.assertEqual(body['account_id'], str(self.personal.pk))
        self.assertEqual(body['payment_channel'], 'alipay')
        row = rows[str(self.order.pk)]
        self.assertEqual(row['discount'], {'amount_minor': 5000, 'label': '加购 5,000 Credits 省 10%'})
        self.assertEqual(row['transaction_reference_display'], '2026110322001…8821')
        self.assertIsNone(row['invoice_file'])

    def test_display_without_discount(self):
        plain = {**SNAPSHOT, 'code': 'fixture-plain', 'amount_minor': 49900}
        plain.pop('discount_minor')
        plain.pop('discount_label')
        order = make_order(self.personal, self.lillian, 'SG-2026-10-0187', snapshot=plain)
        _, rows = self.display()
        self.assertIsNone(rows[str(order.pk)]['discount'])

    def test_invoice_file_states(self):
        review = make_order(self.personal, self.lillian, 'SG-2026-09-0142', disposition='amount_review')
        InvoiceRequest.objects.create(account=self.personal, order=self.order, created_by=self.lillian,
                                      recipient_email='lillian@example.com', title='个人', status='issued',
                                      request_key='fx-invoice', request_hash='fx')
        _, rows = self.display()
        self.assertEqual(rows[str(self.order.pk)]['invoice_file'], 'available')
        self.assertEqual(rows[str(review.pk)]['invoice_file'], 'after_review')

    def test_bill_pdf(self):
        response = self.get('app/billing/invoices/%s/pdf' % self.order.pk)
        self.assertEqual(response.status_code, 200, response.content[:300])
        self.assertEqual(response['Content-Type'], 'application/pdf')
        self.assertIn('attachment', response['Content-Disposition'])
        self.assertIn('SG-2026-11-0042', response['Content-Disposition'])
        self.assertTrue(response.content.startswith(b'%PDF-1.'))
        self.assertTrue(response.content.rstrip().endswith(b'%%EOF'))
        self.assertIn(b'SG-2026-11-0042', response.content)
        self.assertIn(b'449.00', response.content)
        self.assertIn(b'-50.00', response.content)

    def test_invoice_pdf_requires_issued_invoice(self):
        path = 'app/billing/invoices/%s/pdf' % self.order.pk
        self.assert_error(self.get(path, {'document': 'invoice'}), 409, 'STATE_CONFLICT')
        InvoiceRequest.objects.create(account=self.personal, order=self.order, created_by=self.lillian,
                                      recipient_email='lillian@example.com', title='个人', status='sent',
                                      request_key='fx-invoice', request_hash='fx', invoice_reference='INV-0042')
        response = self.get(path, {'document': 'invoice'})
        self.assertEqual(response.status_code, 200, response.content[:300])
        self.assertIn(b'INV-0042', response.content)

    def test_review_order_pdf_conflict(self):
        review = make_order(self.personal, self.lillian, 'SG-2026-09-0142', disposition='amount_review')
        self.assert_error(self.get('app/billing/invoices/%s/pdf' % review.pk, {'document': 'invoice'}),
                          409, 'STATE_CONFLICT')

    def test_unknown_document(self):
        self.assert_error(self.get('app/billing/invoices/%s/pdf' % self.order.pk, {'document': 'receipt'}),
                          422, 'INVALID_REQUEST')

    def test_other_account_order_is_not_found(self):
        foreign = make_order(self.business, self.lillian, 'SG-2026-11-0008')
        self.assert_error(self.get('app/billing/invoices/%s/pdf' % foreign.pk), 404, 'NOT_FOUND')
        self.assert_error(self.get('app/billing/invoices/not-a-uuid/pdf'), 404, 'NOT_FOUND')

    def test_member_cannot_read_business_documents(self):
        order = make_order(self.business, self.lillian, 'SG-2026-11-0009')
        self.login(self.mark, self.business)
        self.assert_error(self.get('app/billing/display'), 403, 'PERMISSION_DENIED')
        self.assert_error(self.get('app/billing/invoices/%s/pdf' % order.pk), 403, 'PERMISSION_DENIED')

    def test_billing_admin_reads_business_documents(self):
        order = make_order(self.business, self.lillian, 'SG-2026-11-0009')
        self.login(self.chen, self.business)
        _, rows = self.display()
        self.assertIn(str(order.pk), rows)
        self.assertEqual(self.get('app/billing/invoices/%s/pdf' % order.pk).status_code, 200)
