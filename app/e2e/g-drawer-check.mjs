import { readFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import path from 'node:path';
const require = createRequire(import.meta.url);
const { chromium } = require(path.join(process.env.PLAYWRIGHT_MODULE, 'index.js'));
const base = 'http://127.0.0.1:4173';
const [name, value] = readFileSync(new URL('../../tmp/dev-session.txt', import.meta.url).pathname, 'utf8').trim().split('=');
const browser = await chromium.launch();
const ctx = await browser.newContext({ viewport: { width: 800, height: 900 } });
await ctx.addCookies([{ name, value, url: base }]);
const page = await ctx.newPage();
const errors = [];
page.on('pageerror', (e) => errors.push('pageerror: ' + e.message));
await page.goto(base + '/tasks/01M7QKMPTEX9JJ19DZQ453FC2X', { waitUntil: 'networkidle' });
await page.getByRole('button', { name: '进度与成果' }).click();
await page.waitForTimeout(300);
await page.screenshot({ path: process.env.OUT });
console.log(JSON.stringify({ errors }));
await browser.close();
