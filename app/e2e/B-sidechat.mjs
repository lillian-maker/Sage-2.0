import { readFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import path from 'node:path';
const require = createRequire(import.meta.url);
const { chromium } = require(path.join(process.env.PLAYWRIGHT_MODULE, 'index.js'));
const out = process.argv[2] || '.';
const base = process.env.SAGE_URL || 'http://127.0.0.1:5182';
const [name, value] = readFileSync(process.env.SAGE_SESSION_FILE || new URL('../../tmp/dev-session.txt', import.meta.url).pathname, 'utf8').trim().split('=');
const browser = await chromium.launch();
const context = await browser.newContext({ viewport: { width: 1440, height: 900 } });
await context.addCookies([{ name, value, url: base }]);
const page = await context.newPage();
const errors = [];
page.on('pageerror', (e) => errors.push('pageerror: ' + e.message));
page.on('response', (r) => r.url().includes('/api/') && r.status() >= 400 && errors.push(`api ${r.status()} ${r.request().method()} ${r.url()}`));
import { seedIds } from './seed-ids.mjs';
const arg = process.argv[3];
const task = arg && arg !== 'auto' ? arg : (await seedIds(base)).richTask;
await page.goto(base + '/tasks/' + task, { waitUntil: 'networkidle' });
await page.locator('.sg-conv__chip').first().click();
await page.waitForTimeout(1500);
await page.waitForLoadState('networkidle');
const input = page.locator('.sg-sidechat .sg-composer__input');
await input.fill('这个价格带包含促销价吗？');
await page.keyboard.press('Enter');
await page.waitForTimeout(1500);
await page.screenshot({ path: path.join(out, '653-2-side-chat-thread.png') });
console.log(JSON.stringify({ url: page.url(), msgs: await page.locator('.sg-sidechat__msg').count(), errors }));
await browser.close();
