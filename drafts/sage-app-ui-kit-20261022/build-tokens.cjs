// Regenerate tokens.css after editing tokens.json. No dependency or build tool required.
const fs=require('node:fs'),path=require('node:path');
const t=JSON.parse(fs.readFileSync(path.join(__dirname,'tokens.json')));
const kebab=s=>s.replace(/[A-Z]/g,m=>'-'+m.toLowerCase());
const lines=['/* Generated from tokens.json. Run node build-tokens.cjs; do not edit this file. */'];
for(const [theme,c]of Object.entries(t.themes)){
 lines.push(theme==='light'?':root, .sage-theme {':':root[data-theme="dark"], .sage-theme[data-theme="dark"] {');
 lines.push('  color-scheme: '+theme+';');
 for(const [k,v]of Object.entries(c))lines.push('  --sg-'+kebab(k)+': '+v+';');
 if(theme==='light'){
  lines.push('  --sg-font: '+t.typography.family+';');
  for(const [k,v]of Object.entries(t.typography.styles))for(const [part,n]of Object.entries(v))lines.push('  --sg-'+kebab(k)+'-'+kebab(part)+': '+n+(part==='weight'?'':'px')+';');
  for(const [k,n]of Object.entries(t.radius))lines.push('  --sg-radius-'+kebab(k)+': '+n+'px;');
  for(const [k,n]of Object.entries(t.size))lines.push('  --sg-size-'+kebab(k)+': '+n+(k==='iconStroke'?'':'px')+';');
  for(const n of t.spacing)lines.push('  --sg-space-'+n+': '+n+'px;');
  for(const k of ['hover','press','enter','exit'])lines.push('  --sg-motion-'+k+': '+t.motion[k]+'ms;');
 }
 lines.push('}');
}
fs.writeFileSync(path.join(__dirname,'tokens.css'),lines.join('\n')+'\n');
console.log('tokens.css generated from the approved light/dark values.');
